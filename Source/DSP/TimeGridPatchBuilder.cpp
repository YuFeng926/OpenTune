TimeGridPatchResult TimeGridPatchBuilder::build(const TimeGridPatchRequest& request)
{
    TimeGridPatchResult result;

    if (request.before == nullptr) {
        result.diagnostic = "AUTO Ref TimeGrid patch requires a source grid";
        return result;
    }

    const double affectedStart = std::min(request.affectedSourceStartSeconds,
                                          request.affectedSourceEndSeconds);
    const double affectedEnd = std::max(request.affectedSourceStartSeconds,
                                        request.affectedSourceEndSeconds);
    if (!std::isfinite(affectedStart) || !std::isfinite(affectedEnd)
        || affectedEnd <= affectedStart) {
        result.diagnostic = "AUTO Ref TimeGrid patch has an invalid affected source range";
        return result;
    }

    const double duration = request.before->totalDurationSeconds();
    std::vector<TimeGridIntent> intents = request.intents;
    std::sort(intents.begin(), intents.end(),
              [](const TimeGridIntent& a, const TimeGridIntent& b) {
                  return a.targetSourceSeconds < b.targetSourceSeconds;
              });

    std::vector<ProjectedHandle> handles;
    handles.reserve(request.before->handles().size() + intents.size());
    std::vector<RemovedHandleRecord> removedHandles;
    removedHandles.reserve(request.before->handles().size());

    for (const auto& handle : request.before->handles()) {
        const bool removeReferenceAuto = handle.kind == HandleKind::ReferenceAuto
                                      && handle.source_seconds > affectedStart
                                      && handle.source_seconds < affectedEnd;
        const bool replaceIdentitySeed = isIdentitySeedHandle(handle)
                                      && handle.source_seconds > affectedStart
                                      && handle.source_seconds < affectedEnd
                                      && matchesIntentSource(handle, intents);
        if (removeReferenceAuto || replaceIdentitySeed) {
            removedHandles.push_back(RemovedHandleRecord{handle, false});
            continue;
        }

        ProjectedHandle projected;
        projected.handle = handle;
        projected.autoGenerated = false;
        projected.desiredOutputSeconds = handle.output_seconds;
        handles.push_back(std::move(projected));
    }

    uint64_t nextId = nextHandleId(handles);
    for (const auto& intent : intents) {
        if (!isFiniteIntent(intent)) {
            result.diagnostic = "AUTO Ref TimeGrid intent contains non-finite values";
            return result;
        }
        if (intent.targetSourceSeconds <= 0.0 || intent.targetSourceSeconds >= duration
            || intent.desiredOutputSeconds <= 0.0 || intent.desiredOutputSeconds >= duration) {
            result.diagnostic = "AUTO Ref TimeGrid intent lies outside target duration";
            return result;
        }
        if (!isInsideAffectedRange(intent.targetSourceSeconds, affectedStart, affectedEnd)) {
            result.diagnostic = "AUTO Ref TimeGrid intent lies outside affected source range";
            return result;
        }
        if (conflictsWithExistingHandle(intent.targetSourceSeconds, handles)) {
            continue;
        }

        ProjectedHandle projected;
        projected.autoGenerated = true;
        projected.desiredOutputSeconds = intent.desiredOutputSeconds;
        projected.handle.id = nextId++;
        projected.handle.source_seconds = intent.targetSourceSeconds;
        projected.handle.output_seconds = intent.desiredOutputSeconds;
        projected.handle.kind = HandleKind::ReferenceAuto;
        projected.handle.locked = false;
        projected.handle.confidence = intent.confidence >= 0.75f ? Confidence::High : Confidence::Default;
        handles.push_back(std::move(projected));
    }

    sortProjectedHandles(handles);

    juce::String projectionNote;
    projectAutoHandles(handles, removedHandles, projectionNote);

    std::vector<TimeHandle> finalHandles;
    finalHandles.reserve(handles.size());
    for (const auto& projected : handles) {
        finalHandles.push_back(projected.handle);
    }

    juce::String validationError;
    if (!TimeGridSnapshot::validate(finalHandles, validationError)) {
        result.diagnostic = validationError;
        return result;
    }

    if (sameHandles(finalHandles, request.before->handles())) {
        result.after = request.before;
        result.success = true;
        result.diagnostic = projectionNote;
        return result;
    }

    result.after = TimeGridSnapshot::makeFromHandles(std::move(finalHandles),
                                                     request.before->revision() + 1);
    if (result.after == nullptr) {
        result.diagnostic = "AUTO Ref produced an invalid TimeGrid";
        return result;
    }

    result.success = true;
    result.diagnostic = projectionNote;
    return result;
}

