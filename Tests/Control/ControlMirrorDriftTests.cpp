void checkHashPrimitives()
{
    using ControlMirror::sha256Hex;
    check(sha256Hex("") == "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
          "sha256 of the empty text");
    check(sha256Hex("abc") == "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", "sha256 of abc");
    check(sha256Hex("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")
              == "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1",
          "sha256 of a text that needs two blocks");

    // Locating a function: braces and quotes in strings and comments, overloads, declarations and calls.
    const std::string sample = "namespace N {\n"
                               "int A::g();\n"
                               "void A::f(int a, const std::string& name = \"x\")\n"
                               "{\n"
                               "    const char* s = \"}\"; // }\n"
                               "    char c = '{';\n"
                               "    if (a) { g(); }\n"
                               "}\n"
                               "void A::h(int a) { one(); }\n"
                               "void A::h(double d) { two(); }\n"
                               "void user() { A::h(1.5); }\n"
                               "static constexpr int kLimit_Extra{1};\n"
                               "static constexpr int kLimit{500};  // comment\n"
                               "}\n";
    const auto f = ControlMirror::extractFunction(sample, "A::f");
    check(f && f->startLine == 3 && f->endLine == 8, "extractFunction spans the function with braces in literals");
    const auto g = ControlMirror::extractFunction(sample, "A::g");
    check(!g, "a declaration is not a definition");
    const auto h = ControlMirror::extractFunction(sample, "A::h(double)");
    check(h && h->text.find("two()") != std::string::npos, "extractFunction tells overloads apart by parameter types");
    const auto limit = ControlMirror::extractStatement(sample, "static constexpr int kLimit");
    check(limit && ControlMirror::normalizedLines(limit->text) == "static constexpr int kLimit{500};",
          "extractStatement stops at the semicolon and does not match a longer identifier");
    const auto original = ControlMirror::hashSymbol(sample, "function", "A::f");
    const auto reformatted = ControlMirror::hashSymbol(
        "\xEF\xBB\xBF"
            + std::string("namespace N {\r\n\r\n   void A::f(int a, const std::string&   name = \"x\")\r\n"
                          "\t{\r\n  const char* s = \"}\"; // }\r\n\r\n    char c = '{';  \r\n"
                          "if (a) {   g(); }\r\n}\r\n}\r\n"),
        "function", "A::f");
    check(original && reformatted && *original == *reformatted,
          "indentation, blank lines, trailing blanks, BOM and CRLF do not change the hash");
    const auto edited = ControlMirror::hashSymbol(
        "void A::f(int a, const std::string& name = \"x\")\n{\n    const char* s = \"}\"; // }\n    char c = '{';\n"
        "    if (a) { g2(); }\n}\n",
        "function", "A::f");
    check(original && edited && *original != *edited, "a change of the body changes the hash");
}

/**
 * For every mirror, a copy of its upstream file with one change inside the mirrored text must give
 * "Changed" (and a message that names the control files, the tests and the update command), and a copy that
 * only differs in formatting must give "Unchanged".
 */
void checkDriftIsDetected(const fs::path& root, const std::vector<Mirror>& mirrors, const std::string& program)
{
    const auto stamp = std::chrono::steady_clock::now().time_since_epoch().count();
    const fs::path temporary = fs::temp_directory_path() / ("ot-mirror-drift-" + std::to_string(stamp));
    std::error_code ignored;
    for (const auto& mirror : mirrors) {
        const auto raw = readFile(root / fs::path(mirror.file));
        if (!raw)
            continue; // reported by the real check
        const std::string text = ControlMirror::normalizeSource(*raw);
        const auto located = mirror.kind == "statement" ? ControlMirror::extractStatement(text, mirror.symbol)
                                                        : ControlMirror::extractFunction(text, mirror.symbol);
        if (!located)
            continue;
        const auto at = text.find(located->text);
        if (!check(at != std::string::npos, mirror.id + ": the located text is part of the file"))
            continue;
        const fs::path target = temporary / fs::path(mirror.file);
        fs::create_directories(target.parent_path(), ignored);

        // A change inside the mirrored text.
        std::string changed = located->text;
        if (mirror.kind == "statement")
            changed.insert(changed.size() - 1, "+1");
        else
            changed.insert(changed.find('{') + 1, "\n    int mirrorDriftProbe = 0;\n");
        writeFile(target, text.substr(0, at) + changed + text.substr(at + located->text.size()));
        const auto drift = checkMirror(temporary, mirror);
        check(drift.status == Outcome::Status::Changed && drift.current != mirror.sha256,
              mirror.id + ": a change inside " + mirror.symbol + " is detected");
        const auto message = driftMessage(mirror, drift, program);
        check(message.find(mirror.symbol) != std::string::npos
                  && message.find(mirror.control.front().file) != std::string::npos
                  && message.find(mirror.tests.front()) != std::string::npos
                  && message.find("--update") != std::string::npos,
              mirror.id + ": the message names the function, the control file, the tests and the update command");

        // A change of formatting only: indentation, trailing blanks, blank lines, CRLF and a BOM.
        std::string formatted;
        std::istringstream lines(located->text);
        for (std::string line; std::getline(lines, line);)
            formatted += "\t\t  " + line + "   \t\r\n\r\n";
        formatted.resize(formatted.size() - 4); // the last line break, as the text had none after the last line
        writeFile(target, "\xEF\xBB\xBF" + text.substr(0, at) + formatted + text.substr(at + located->text.size()));
        const auto same = checkMirror(temporary, mirror);
        check(same.status == Outcome::Status::Unchanged && same.current == mirror.sha256,
              mirror.id + ": a change of formatting only is not a drift");

        // The symbol gone (renamed): reported, with the hand-edit hint.
        writeFile(target, std::string("// nothing here\n"));
        const auto gone = checkMirror(temporary, mirror);
        check(gone.status == Outcome::Status::MissingSymbol, mirror.id + ": a missing symbol is reported");
        fs::remove(target, ignored);
    }
    fs::remove_all(temporary, ignored);
}

