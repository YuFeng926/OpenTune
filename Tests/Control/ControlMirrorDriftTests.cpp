// ControlMirrorDriftTests: the control API repeats the steps of some upstream functions (it "mirrors" them,
// see Source/Control/MIRRORS.md). Source/Control/mirror-map.json lists them with a hash of each function's
// normalised text. This test hashes the same text in the source tree and fails when one differs, so that
// whoever changed an upstream function is told which file of Source/Control to bring in line, which tests to
// run, and how to record the new hash. It also checks that MIRRORS.md says what mirror-map.json says, that
// the control files and tests named there exist, and (self-test) that a change inside a mirrored function
// turns the check red while a change of formatting only does not.
//
// Standard library and Source/Control/ControlJson.cpp only; no JUCE.
//
// Usage: OpenTuneControlMirrorDriftTests [--root <source tree>] [--update]
//   --update  rewrites the hashes of mirror-map.json and MIRRORS.md to what the source tree has now. Review
//             the mirrored code first: the hash only says that the upstream text has not changed since.

