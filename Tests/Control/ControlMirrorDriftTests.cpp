int failures = 0;

void fail(const std::string& message)
{
    ++failures;
    std::cerr << message << std::endl;
}

bool check(bool ok, const std::string& what)
{
    if (!ok)
        fail("    FAILED " + what);
    return ok;
}

const char* const kMapPath = "Source/Control/mirror-map.json";
const char* const kDocPath = "Source/Control/MIRRORS.md";
const char* const kCmakePath = "cmake/OpenTuneControl.cmake";
const char* const kTableBegin =
    "<!-- mirror-table:begin (generated by ControlMirrorDriftTests, update option; do not edit) -->";
const char* const kTableEnd = "<!-- mirror-table:end -->";

struct ControlRef
{
    std::string file;
    std::vector<std::string> symbols;
};

struct Mirror
{
    std::string id;
    std::string group;
    std::string file;
    std::string symbol;
    std::string kind;
    std::string normalization;
    std::string sha256;
    std::vector<ControlRef> control;
    std::vector<std::string> tests;
    std::string note;
    std::string noteZh;
};

std::optional<std::string> readFile(const fs::path& path)
{
    std::ifstream in(path, std::ios::binary);
    if (!in)
        return std::nullopt;
    return std::string(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
}

bool writeFile(const fs::path& path, const std::string& contents)
{
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    out.write(contents.data(), static_cast<std::streamsize>(contents.size()));
    return static_cast<bool>(out);
}

std::string stringMember(const JsonValue& object, const char* name, bool& ok)
{
    const JsonValue* member = object.find(name);
    if (member == nullptr || !member->isString() || member->text().empty()) {
        ok = false;
        return {};
    }
    return member->text();
}

std::vector<std::string> stringList(const JsonValue& object, const char* name, bool& ok)
{
    std::vector<std::string> out;
    const JsonValue* member = object.find(name);
    if (member == nullptr || !member->isArray() || member->size() == 0) {
        ok = false;
        return out;
    }
    for (std::size_t i = 0; i < member->size(); ++i) {
        if (!member->at(i).isString() || member->at(i).text().empty())
            ok = false;
        else
            out.push_back(member->at(i).text());
    }
    return out;
}

/** Reads the mirror list from the parsed mirror-map.json; a malformed entry fails the test. */
std::vector<Mirror> loadMirrors(const JsonValue& root)
{
    std::vector<Mirror> mirrors;
    const JsonValue* list = root.find("mirrors");
    if (!check(list != nullptr && list->isArray() && list->size() > 0,
               "mirror-map.json has a non-empty \"mirrors\" array"))
        return mirrors;
    for (std::size_t i = 0; i < list->size(); ++i) {
        const JsonValue& item = list->at(i);
        bool ok = item.isObject();
        Mirror mirror;
        if (ok) {
            mirror.id = stringMember(item, "id", ok);
            mirror.group = stringMember(item, "group", ok);
            mirror.note = stringMember(item, "note", ok);
            mirror.noteZh = stringMember(item, "noteZh", ok);
            mirror.tests = stringList(item, "tests", ok);
            const JsonValue* upstream = item.find("upstream");
            if (upstream != nullptr && upstream->isObject()) {
                mirror.file = stringMember(*upstream, "file", ok);
                mirror.symbol = stringMember(*upstream, "symbol", ok);
                mirror.kind = stringMember(*upstream, "kind", ok);
                mirror.normalization = stringMember(*upstream, "normalization", ok);
                mirror.sha256 = stringMember(*upstream, "sha256", ok);
            } else {
                ok = false;
            }
            const JsonValue* control = item.find("control");
            if (control != nullptr && control->isArray() && control->size() > 0) {
                for (std::size_t c = 0; c < control->size(); ++c) {
                    ControlRef ref;
                    if (control->at(c).isObject()) {
                        ref.file = stringMember(control->at(c), "file", ok);
                        ref.symbols = stringList(control->at(c), "symbols", ok);
                    } else {
                        ok = false;
                    }
                    mirror.control.push_back(std::move(ref));
                }
            } else {
                ok = false;
            }
        }
        if (!check(ok, "mirrors[" + std::to_string(i)
                           + "] has every field (id, group, upstream{file, symbol, kind, "
                             "normalization, sha256}, control[{file, symbols}], tests, "
                             "note, noteZh)"))
            continue;
        const bool known = (mirror.kind == "function" && mirror.normalization == "fn-v1")
                           || (mirror.kind == "statement" && mirror.normalization == "stmt-v1");
        check(known, mirror.id + ": kind/normalization is function/fn-v1 or statement/stmt-v1");
        check(mirror.sha256.size() == 64 && mirror.sha256.find_first_not_of("0123456789abcdef") == std::string::npos,
              mirror.id + ": sha256 is 64 lower-case hexadecimal digits");
        check(mirror.file.rfind("Source/", 0) == 0 && mirror.file.rfind("Source/Control/", 0) != 0,
              mirror.id + ": the upstream file is under Source/ and not part of the control API");
        mirrors.push_back(std::move(mirror));
    }
    std::set<std::string> ids;
    std::set<std::string> hashes;
    for (const auto& mirror : mirrors) {
        check(ids.insert(mirror.id).second, "mirror id " + mirror.id + " is unique");
        check(hashes.insert(mirror.sha256).second,
              mirror.id + ": its hash differs from every other (--update replaces by hash)");
    }
    return mirrors;
}

struct Outcome
{
    enum class Status {
        Unchanged,
        Changed,
        MissingFile,
        MissingSymbol
    };
    Status status = Status::Unchanged;
    std::string current;
};

/** Hashes the mirrored text in the tree under root and compares it with the recorded hash. */
Outcome checkMirror(const fs::path& root, const Mirror& mirror)
{
    Outcome outcome;
    const auto contents = readFile(root / fs::path(mirror.file));
    if (!contents) {
        outcome.status = Outcome::Status::MissingFile;
        return outcome;
    }
    const auto hash = ControlMirror::hashSymbol(*contents, mirror.kind, mirror.symbol);
    if (!hash) {
        outcome.status = Outcome::Status::MissingSymbol;
        return outcome;
    }
    outcome.current = *hash;
    outcome.status = *hash == mirror.sha256 ? Outcome::Status::Unchanged : Outcome::Status::Changed;
    return outcome;
}

std::string controlFilesText(const Mirror& mirror)
{
    std::string text;
    for (const auto& ref : mirror.control) {
        if (!text.empty())
            text += "; ";
        text += ref.file + " (";
        for (std::size_t i = 0; i < ref.symbols.size(); ++i)
            text += (i == 0 ? "" : ", ") + ref.symbols[i];
        text += ")";
    }
    return text;
}

std::string testsRegex(const Mirror& mirror)
{
    std::string text = "^(";
    for (std::size_t i = 0; i < mirror.tests.size(); ++i)
        text += (i == 0 ? "" : "|") + mirror.tests[i];
    return text + ")$";
}

/** What a failing check tells the person who changed the upstream function. */
std::string driftMessage(const Mirror& mirror, const Outcome& outcome, const std::string& program)
{
    std::ostringstream out;
    out << "  MIRROR DRIFT [" << mirror.id << "]\n";
    if (outcome.status == Outcome::Status::Changed) {
        out << "  You changed " << mirror.symbol << " (" << mirror.file << ").\n";
    } else if (outcome.status == Outcome::Status::MissingFile) {
        out << "  The file " << mirror.file << " is gone (it mirrored " << mirror.symbol << ").\n";
    } else {
        out << "  " << mirror.symbol << " is no longer found in " << mirror.file << " (moved, renamed or removed).\n";
    }
    out << "  The control API repeats its steps. Bring this in line with the change: " << controlFilesText(mirror)
        << ".\n";
    out << "  Then run: ctest -R \"" << testsRegex(mirror) << "\"\n";
    if (outcome.status == Outcome::Status::Changed) {
        out << "  When the mirrored code is reviewed and the tests pass, record the new hash: \"" << program
            << "\" --update\n";
    } else {
        out << "  Then correct the \"upstream\" entry of " << mirror.id << " in " << kMapPath
            << " by hand (--update only replaces hashes).\n";
    }
    out << "  (你改了 " << mirror.symbol << "，请同步 " << controlFilesText(mirror) << " 并跑 ctest -R \""
        << testsRegex(mirror) << "\"，然后更新哈希：\"" << program << "\" --update)\n";
    if (outcome.status == Outcome::Status::Changed)
        out << "  recorded " << mirror.sha256 << "\n  current  " << outcome.current << "\n";
    out << "  Details: Source/Control/MIRRORS.md";
    return out.str();
}

// ---- MIRRORS.md --------------------------------------------------------------------------------------------

std::string cell(std::string text)
{
    std::string out;
    for (const char c : text)
        out += c == '|' ? std::string("\\|") : std::string(1, c);
    return out;
}

/** The generated part of MIRRORS.md: one table row per mirror, from mirror-map.json. */
std::string renderTable(const std::vector<Mirror>& mirrors)
{
    std::string out;
    out += std::string(kTableBegin) + "\n";
    out += "| Id | Upstream function / 上游函数 | Control API / 接口层 | Tests / 测试 | sha256 | Note / 说明 |\n";
    out += "|---|---|---|---|---|---|\n";
    for (const auto& mirror : mirrors) {
        std::string control;
        for (const auto& ref : mirror.control) {
            if (!control.empty())
                control += "<br>";
            control += "`" + ref.file + "`: ";
            for (std::size_t i = 0; i < ref.symbols.size(); ++i)
                control += std::string(i == 0 ? "" : ", ") + "`" + cell(ref.symbols[i]) + "`";
        }
        std::string tests;
        for (std::size_t i = 0; i < mirror.tests.size(); ++i)
            tests += std::string(i == 0 ? "" : "<br>") + "`" + mirror.tests[i] + "`";
        out += "| `" + mirror.id + "` | `" + mirror.file + "`<br>`" + cell(mirror.symbol) + "` (" + mirror.normalization
               + ") | " + control + " | " + tests + " | `" + mirror.sha256 + "` | " + cell(mirror.note) + "<br>"
               + cell(mirror.noteZh) + " |\n";
    }
    out += kTableEnd;
    return out;
}

/** Position and length of the generated block (markers included) in the text of MIRRORS.md. */
std::optional<std::pair<std::size_t, std::size_t>> tableBlock(const std::string& doc)
{
    const auto begin = doc.find(kTableBegin);
    const auto end = doc.find(kTableEnd);
    if (begin == std::string::npos || end == std::string::npos || end < begin)
        return std::nullopt;
    return std::make_pair(begin, end + std::string(kTableEnd).size() - begin);
}

std::string lf(const std::string& text)
{
    return ControlMirror::normalizeSource(text);
}

// ---- Checks that need no upstream file ---------------------------------------------------------------------

/** Whether the word occurs in the text as a whole identifier. */
bool containsWord(const std::string& text, const std::string& word)
{
    for (auto at = text.find(word); at != std::string::npos; at = text.find(word, at + 1)) {
        const bool before = at == 0 || !ControlMirror::detail::isIdent(text[at - 1]);
        const bool after = at + word.size() >= text.size() || !ControlMirror::detail::isIdent(text[at + word.size()]);
        if (before && after)
            return true;
    }
    return false;
}

/** The control files and tests that a mirror names exist. */
void checkReferences(const fs::path& root, const Mirror& mirror, const std::string& cmake)
{
    for (const auto& ref : mirror.control) {
        const auto contents = readFile(root / fs::path(ref.file));
        if (!check(contents.has_value(), mirror.id + ": the control file " + ref.file + " exists"))
            continue;
        for (const auto& symbol : ref.symbols) {
            const auto scope = symbol.rfind("::");
            const std::string word = scope == std::string::npos ? symbol : symbol.substr(scope + 2);
            check(containsWord(*contents, word), mirror.id + ": " + ref.file + " mentions " + symbol);
        }
    }
    for (const auto& test : mirror.tests) {
        const std::string processorPrefix = "ControlProcessorTests.";
        bool registered = false;
        if (test.rfind(processorPrefix, 0) == 0) {
            const std::string scenario = test.substr(processorPrefix.size());
            registered = cmake.find("\"" + scenario + "|") != std::string::npos
                         || cmake.find("\"" + scenario + "\"") != std::string::npos;
        } else {
            registered = cmake.find("add_test(NAME " + test) != std::string::npos;
        }
        check(registered, mirror.id + ": the test " + test + " is registered in " + kCmakePath);
    }
}

